def load_manifest(report: Report) -> dict:
    if not MANIFEST_PATH.exists():
        report.error(f"找不到清单文件: {MANIFEST_PATH.relative_to(REPO)}")
        return {}
    try:
        raw = MANIFEST_PATH.read_text(encoding="utf-8")
    except OSError as exc:
        report.error(f"读取清单失败: {exc}")
        return {}
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        report.error(f"status.json 不是合法 JSON: {exc}")
        return {}
    if data.get("schemaVersion") != 1:
        report.error(f"status.json 的 schemaVersion 必须是 1，当前是 {data.get('schemaVersion')!r}")
    return data


def known_pins() -> set:
    """从 pin-cards.css 里读出所有已定义配色的 pin 名字。"""
    if not PIN_CSS.exists():
        return set()
    return set(PIN_RULE_RE.findall(PIN_CSS.read_text(encoding="utf-8")))


def validate_manifest(manifest: dict, report: Report) -> None:
    pins = known_pins()
    if not pins:
        report.warn(f"没有从 {PIN_CSS.relative_to(REPO)} 读到任何 pin 配色规则，pin 校验已跳过")

    site = manifest.get("site") or {}
    for key in ("title", "baseURL"):
        if not site.get(key):
            report.error(f"site.{key} 缺失")

    # 同时校验 hugo.yaml 与清单一致，避免两份配置各说各话
    hugo_yaml = DOCS / "hugo.yaml"
    if hugo_yaml.exists() and site.get("baseURL"):
        text = hugo_yaml.read_text(encoding="utf-8")
        m = re.search(r'^baseURL:\s*"?([^"\n]+)"?\s*$', text, re.M)
        if m and m.group(1).strip().rstrip("/") != site["baseURL"].rstrip("/"):
            report.error(
                "docs/hugo.yaml 的 baseURL 与 status.json 的 site.baseURL 不一致："
                f"{m.group(1).strip()} vs {site['baseURL']}"
            )

    sections = manifest.get("sections") or []
    posts = manifest.get("posts") or []

    if not sections and not posts:
        report.error("清单里既没有 sections 也没有 posts，没有任何内容会被发布")

    section_ids = set()
    for sec in sections:
        where = f"section {sec.get('id')!r}"
        for key in ("id", "slug", "title"):
            if not sec.get(key):
                report.error(f"{where} 缺少必填字段 {key}")
        sid = sec.get("id")
        if sid in section_ids:
            report.error(f"{where} 的 id 重复")
        section_ids.add(sid)
        if not SLUG_RE.match(str(sec.get("slug", ""))):
            report.error(f"{where} 的 slug 必须是小写 ASCII（kebab-case），当前 {sec.get('slug')!r}")
        if sec.get("pin") and pins and sec["pin"] not in pins:
            report.error(
                f"{where} 用了未定义配色的 pin={sec['pin']!r}；"
                f"可选值：{', '.join(sorted(pins))}"
            )
        check_date(sec.get("date"), where, report)

    for sec in sections:
        parent = sec.get("parent")
        if parent and parent not in section_ids:
            report.error(f"section {sec.get('id')!r} 的 parent={parent!r} 不存在")

    seen_paths = {}
    for post in posts:
        where = f"post {post.get('id') or post.get('slug')!r}"
        for key in ("source", "section", "slug", "title"):
            if not post.get(key):
                report.error(f"{where} 缺少必填字段 {key}")
        if post.get("section") not in section_ids:
            report.error(f"{where} 的 section={post.get('section')!r} 不存在")
        if not SLUG_RE.match(str(post.get("slug", ""))):
            report.error(f"{where} 的 slug 必须是小写 ASCII（kebab-case），当前 {post.get('slug')!r}")
        check_date(post.get("date"), where, report)
        src = post.get("source")
        if src and not (REPO / src).exists():
            report.error(f"{where} 的 source 不存在: {src}")
        if post.get("pin") and pins and post["pin"] not in pins:
            report.error(f"{where} 用了未定义配色的 pin={post['pin']!r}")

        out = "posts/{}/{}".format(section_path(manifest, post.get("section")), post.get("slug"))
        if out in seen_paths:
            report.error(f"{where} 与 {seen_paths[out]} 的输出路径冲突: {out}")
        seen_paths[out] = where


def check_date(value, where: str, report: Report) -> None:
    if not value:
        report.error(f"{where} 缺少 date（笔记没有 git 历史时无法从别处推断，必须显式给出）")
        return
    if not DATE_RE.match(str(value)):
        report.error(f"{where} 的 date 必须是 YYYY-MM-DD，当前 {value!r}")
        return
    # buildFuture=false 会让未来日期的页面直接从构建结果里消失，
    # 表现是首页有卡片但点进去 404，所以这里必须提前拦住。
    today = _dt.date.today()
    try:
        d = _dt.date.fromisoformat(str(value))
    except ValueError:
        report.error(f"{where} 的 date 不是合法日期: {value!r}")
        return
    if d > today:
        report.warn(f"{where} 的 date={value} 在未来（今天是 {today.isoformat()}），"
                    "该页面不会出现在构建结果里")


