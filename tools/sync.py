def toml_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        # json 的转义是 TOML basic string 的子集（\uXXXX、\n、\" 都合法）
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(json.dumps(v, ensure_ascii=False) for v in value) + "]"
    raise TypeError(f"无法写入 frontmatter 的类型: {type(value)!r}")


def frontmatter_toml(fields: dict) -> str:
    lines = ["+++"]
    for key, value in fields.items():
        if value is None:
            continue
        lines.append(f"{key} = {toml_value(value)}")
    lines.append("+++")
    return "\n".join(lines)


def header(source_rel: str) -> str:
    return f"{GEN_MARK} from {source_rel}; DO NOT EDIT -->"


