# --------------------------------------------------------------------------

def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="把 Obsidian 笔记同步成 docs/ 下的 Hugo 站点内容",
    )
    parser.add_argument("--check", action="store_true", help="只校验并比对，不写文件")
    parser.add_argument("--strict", action="store_true", help="把警告也当作失败")
    parser.add_argument("--clean", action="store_true", help="先清空 docs/content 再生成")
    parser.add_argument("--serve", action="store_true", help="生成后启动 hugo server")
    args = parser.parse_args(argv)

    report = Report()
    manifest = load_manifest(report)
    if manifest:
        validate_manifest(manifest, report)

    outputs = []
    if manifest and not report.errors:
        outputs = build_plan(manifest, report)
        audit_scan_roots(manifest, report)

    if report.errors:
        print_report(report, outputs)
        print("\n同步失败：请先修掉上面的 error。", file=sys.stderr)
        return 1

    if args.clean and not args.check:
        clean_content(report)

    write_outputs(outputs, report, dry_run=args.check)

    print_report(report, outputs)
    if args.check:
        print("\n校验通过（未写入任何文件）。")
    if args.strict and report.warnings:
        print(f"\n--strict：有 {len(report.warnings)} 条警告，视为失败。", file=sys.stderr)
        return 1

    if args.serve:
        if shutil.which("hugo") is None:
            print("\n没有找到 hugo，无法预览。macOS 上可以 `brew install hugo` 安装。", file=sys.stderr)
            return 1
        return subprocess.call(["hugo", "serve", "--source", str(DOCS)])
    return 0


def print_report(report: Report, outputs) -> None:
    for msg in report.warnings:
        print(f"WARN  {msg}")
    for msg in report.errors:
        print(f"ERROR {msg}", file=sys.stderr)
    for msg in report.notes:
        print(f"      {msg}")
    if outputs:
        print(f"\n共 {len(outputs)} 个页面：")
        for out in outputs:
            print(f"  {out.path.relative_to(REPO)}")
    summary = f"\n{len(outputs)} 个页面 / {len(report.warnings)} 条警告 / {len(report.errors)} 个错误"
    print(summary)


if __name__ == "__main__":
    sys.exit(main())
