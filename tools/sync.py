def write_outputs(outputs, report: Report, dry_run: bool) -> int:
    expected = {o.path.resolve() for o in outputs}
    stale = []

    # 清掉上一轮生成、这一轮已不在清单里的文件（只删带生成标记的）
    if CONTENT.exists():
        for path in CONTENT.rglob("*.md"):
            if path.resolve() in expected:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except OSError:
                continue
            if text.lstrip().startswith(GEN_MARK) or GEN_MARK in text[:400]:
                stale.append(path)

    drift = []
    for out in outputs:
        if out.path.exists():
            try:
                if out.path.read_text(encoding="utf-8") != out.text:
                    drift.append(out.path)
            except OSError:
                drift.append(out.path)
        else:
            drift.append(out.path)

    if dry_run:
        if drift:
            report.note(
                f"docs/content 有 {len(drift)} 个文件与当前笔记不一致，"
                "本地跑一次 python3 tools/sync.py 即可同步"
            )
        if stale:
            report.note(f"有 {len(stale)} 个已废弃的生成文件待清理")
        return 0

    if stale:
        for path in stale:
            path.unlink()
        report.note(f"清理了 {len(stale)} 个已废弃的生成文件")

    copied = 0
    for out in outputs:
        out.path.parent.mkdir(parents=True, exist_ok=True)
        out.path.write_text(out.text, encoding="utf-8")
        for image in out.images:
            target = out.path.parent / image.name
            if not target.exists() or target.stat().st_mtime < image.stat().st_mtime:
                shutil.copy2(image, target)
                copied += 1
    report.note(f"写入了 {len(outputs)} 个文件，复制了 {copied} 张图片")
    return 0


def clean_content(report: Report) -> None:
    if CONTENT.exists():
        shutil.rmtree(CONTENT)
        report.note("已清空 docs/content")


