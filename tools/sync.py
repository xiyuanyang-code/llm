#!/usr/bin/env python3
"""把仓库里的 Obsidian 笔记同步成 docs/ 下的 Hugo 站点内容。

职责边界：
  - 笔记（model_arch/、infra/ …）永远是唯一的内容真相来源，本工具**不修改笔记**。
  - 本站点是唯一的内容清单，决定「发布什么、每篇的元信息是什么」。
  - 生成物（docs/content/**）不入库，由本地或 CI 每次运行本脚本产出。

用法：
    python3 tools/sync.py              # 生成 docs/content/
    python3 tools/sync.py --check      # 只校验并比对，不写文件（CI 第一步用）
    python3 tools/sync.py --strict     # 把 warning 也当成失败
    python3 tools/sync.py --clean      # 先清空 docs/content 再生成
    python3 tools/sync.py --serve      # 生成后启动 hugo server 本地预览
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MANIFEST_PATH = REPO / "tools" / "status.json"
DOCS = REPO / "docs"
CONTENT = DOCS / "content"
PIN_CSS = DOCS / "assets" / "css" / "extended" / "pin-cards.css"

GEN_MARK = "<!-- generated by tools/sync.py"
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
# 开围栏：最多 3 个前导空格 + 3 个以上 ` 或 ~
FENCE_OPEN_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
PIN_RULE_RE = re.compile(r"^\.post-entry\.pin-([A-Za-z0-9_-]+)", re.M)
# 行内 markdown 链接，指向 .md（排除图片、外链、纯锚点）
MD_LINK_RE = re.compile(r"(?<!!)\[([^\]\n]*)\]\((?!https?:|mailto:|#)([^)\n]+?\.md)(#[^)\n]*)?\)")
EMBED_RE = re.compile(r"!\[\[([^\]\n]+?)\]\]")
WIKILINK_RE = re.compile(r"(?<!!)\[\[([^\]\n]+?)\]\]")
HIGHLIGHT_RE = re.compile(r"==(?=\S)([^\n=]+?)(?<=\S)==")
H1_RE = re.compile(r"^#\s+")


class Report:
    """收集错误与警告。错误会让进程退出码非 0，警告默认只是提示。"""

    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.notes: list[str] = []

    def error(self, msg: str) -> None:
        self.errors.append(msg)

    def warn(self, msg: str) -> None:
        self.warnings.append(msg)

    def note(self, msg: str) -> None:
        self.notes.append(msg)


