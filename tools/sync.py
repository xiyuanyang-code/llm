def section_path(manifest: dict, section_id: str) -> str:
    """把一个 section 的 id 展开成 content/posts 下的相对路径，支持嵌套。"""
    by_id = {s.get("id"): s for s in manifest.get("sections") or []}
    parts = []
    seen = set()
    cur = section_id
    while cur:
        if cur in seen:
            break
        seen.add(cur)
        sec = by_id.get(cur)
        if not sec:
            break
        parts.append(sec.get("slug"))
        cur = sec.get("parent")
    return "/".join(reversed(parts))


