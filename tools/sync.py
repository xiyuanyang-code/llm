def split_fences(text: str):
    """把正文切成 (is_code, lines) 段。所有语法重写只作用于非代码段。

    这一步是整个转换器的地基：slime-training.md 的 python 代码块里有
    `if self.role == "critic":` 这种 == 比较运算符，如果先做高亮替换就会把
    代码改坏。
    """
    lines = text.split("\n")
    out = []
    buf = []
    i = 0
    total = len(lines)
    while i < total:
        m = FENCE_OPEN_RE.match(lines[i])
        if not m:
            buf.append(lines[i])
            i += 1
            continue
        if buf:
            out.append((False, buf))
            buf = []
        fence = m.group(1)
        char = fence[0]
        close_re = re.compile(r"^ {0,3}" + re.escape(char) + r"{%d,}[ \t]*$" % len(fence))
        block = [lines[i]]
        i += 1
        closed = False
        while i < total:
            block.append(lines[i])
            if close_re.match(lines[i]):
                i += 1
                closed = True
                break
            i += 1
        if not closed:
            out.append((True, block))
            return out, True
        out.append((True, block))
    if buf:
        out.append((False, buf))
    return out, False


def split_inline(text: str):
    """把非代码段的文本切成 (kind, text)，kind ∈ {plain, code, math}。

    被保护起来的片段（行内代码、行内公式、`$$…$$` 块）不会被任何重写碰到。
    """
    parts = []
    i = 0
    total = len(text)
    start = 0
    while i < total:
        if text[i] == "\\":
            i += 2
            continue
        # 块级公式，可以跨行，优先于行内 $...$
        if text.startswith("$$", i):
            end = text.find("$$", i + 2)
            if end != -1:
                parts.append(("plain", text[start:i]))
                parts.append(("math", text[i:end + 2]))
                i = end + 2
                start = i
                continue
            i += 2
            continue
        if text[i] == "`":
            j = i
            while j < total and text[j] == "`":
                j += 1
            ticks = text[i:j]
            end = text.find(ticks, j)
            if end != -1:
                parts.append(("plain", text[start:i]))
                parts.append(("code", text[i:end + len(ticks)]))
                i = end + len(ticks)
                start = i
                continue
            i = j
            continue
        if text[i] == "$":
            nl = text.find("\n", i)
            end = text.find("$", i + 1)
            if end != -1 and end > i + 1 and (nl == -1 or end < nl):
                parts.append(("plain", text[start:i]))
                parts.append(("math", text[i:end + 1]))
                i = end + 1
                start = i
                continue
            i += 1
            continue
        i += 1
    parts.append(("plain", text[start:]))
    return parts


class Doc:
    """一篇待转换的文档（文章或专题落地页）。"""

    def __init__(self, manifest, report: Report, source_rel: str, out_dir: Path,
                 link_map: dict, demote_h1: bool = True) -> None:
        self.manifest = manifest
        self.report = report
        self.source_rel = source_rel
        self.out_dir = out_dir
        self.link_map = link_map
        self.demote_h1 = demote_h1
        self.images: list[Path] = []
        self.label = source_rel

    # -- 图片 ---------------------------------------------------------------
    def _asset(self, name: str):
        root = REPO / (self.manifest.get("assetRoot") or "images")
        candidate = root / name
        if candidate.exists():
            return candidate
        # 兼容笔记里写了子目录路径的情况
        candidate = REPO / name
        if candidate.exists():
            return candidate
        return None

    def _rewrite_embed(self, match: re.Match) -> str:
        target, _, alias = match.group(1).partition("|")
        name = target.strip()
        alt = alias.strip()
        if alt.isdigit():
            alt = ""
        path = self._asset(name)
        if path is None:
            self.report.warn(f"图片缺失: {name}（来自 {self.source_rel}），已插入占位")
            return f'<span class="asset-missing">⚠️ 图片缺失：<code>{name}</code></span>'
        self.images.append(path)
        label = alt or name
        # 相对路径 + leaf page bundle：PaperMod 的 render-image.html 会通过
        # .PageInner.Resources 解析它，从而带上 /llm/ 前缀，站点换路径也不会裂。
        return f"![{label}]({path.name})"

    def _rewrite_link(self, match: re.Match) -> str:
        text, target, frag = match.group(1), match.group(2), match.group(3) or ""
        base = os.path.dirname(self.source_rel)
        normalized = os.path.normpath(os.path.join(base, target)).replace(os.sep, "/")
        dest = self.link_map.get(normalized)
        if dest is None:
            self.report.error(
                f"{self.source_rel} 里的内部链接指向未发布的笔记: {target}"
                "（要么把它加进 status.json，要么改成外部链接）"
            )
            return match.group(0)
        # 用 relref 而不是写死的 URL：Hugo 会自动补上 /llm/ 前缀，
        # 目标不存在时构建会直接报错，而不是产出一个 404 链接。
        return f'[{text}]({{{{< relref "{dest}" >}}}}{frag})'

    def _rewrite_plain(self, chunk: str) -> str:
        if "![" in chunk:
            chunk = EMBED_RE.sub(self._rewrite_embed, chunk)
        if "](" in chunk:
            chunk = MD_LINK_RE.sub(self._rewrite_link, chunk)
        if "[[" in chunk:
            def wikilink(m):
                self.report.warn(
                    f"{self.source_rel} 里有 Obsidian wikilink {m.group(0)}，"
                    "转换器不会猜测目标，已原样保留"
                )
                return m.group(0)
            chunk = WIKILINK_RE.sub(wikilink, chunk)
        if "==" in chunk:
            if chunk.count("==") % 2:
                self.report.note(f"{self.source_rel} 有一行 == 无法配对，已原样保留: {chunk.strip()[:60]}")
            chunk = HIGHLIGHT_RE.sub(lambda m: f"<mark>{m.group(1)}</mark>", chunk)
        return chunk

    def body(self, text: str) -> str:
        text = text.replace("\r\n", "\n").replace("\r", "\n")
        blocks, unclosed = split_fences(text)
        if unclosed:
            self.report.warn(f"{self.source_rel} 有未闭合的代码围栏，其后的内容都按代码处理")

        out = []
        for is_code, lines in blocks:
            if is_code:
                out.append("\n".join(lines))
                continue
            if self.demote_h1:
                # 笔记正文里的 H1 会和 PaperMod 的页面标题打架，降一级。
                lines = [H1_RE.sub("## ", ln) if H1_RE.match(ln) else ln for ln in lines]
            chunk = "\n".join(lines)
            out.append("".join(
                part if kind != "plain" else self._rewrite_plain(part)
                for kind, part in split_inline(chunk)
            ))
        body = "\n".join(out).strip("\n")
        return body + "\n" if body else ""


