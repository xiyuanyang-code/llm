class Output:
    def __init__(self, path: Path, text: str, images=None) -> None:
        self.path = path
        self.text = text
        self.images = images or []


def build_plan(manifest: dict, report: Report):
    outputs = []
    link_map = {}

    # 先建链接映射，内部链接重写需要知道每个源文件最终落在哪
    for post in manifest.get("posts") or []:
        sec_path = section_path(manifest, post["section"])
        link_map[post["source"]] = f"posts/{sec_path}/{post['slug']}/index.md"
    for sec in manifest.get("sections") or []:
        if sec.get("index_source"):
            link_map[sec["index_source"]] = f"posts/{section_path(manifest, sec['id'])}/_index.md"

    # 专题落地页
    for sec in manifest.get("sections") or []:
        rel_dir = Path("posts") / section_path(manifest, sec["id"])
        out_dir = CONTENT / rel_dir
        src = sec.get("index_source")
        if src:
            doc = Doc(manifest, report, src, out_dir, link_map)
            body = doc.body((REPO / src).read_text(encoding="utf-8"))
            images = doc.images
        else:
            body = f"> {sec.get('description') or '本专题内容正在整理中。'}\n"
            images = []
        fields = {
            "title": sec.get("title"),
            "date": sec.get("date"),
            "description": sec.get("description"),
            "tags": sec.get("tags"),
            "weight": sec.get("weight"),
            "pin": sec.get("pin"),
            "toc": sec.get("toc"),
            "draft": sec.get("draft"),
        }
        text = frontmatter_toml(fields) + "\n\n" + header(src or f"section:{sec['id']}") + "\n\n" + body
        outputs.append(Output(out_dir / "_index.md", text, images))

    # 文章
    for post in manifest.get("posts") or []:
        src = post["source"]
        sec_path = section_path(manifest, post["section"])
        out_dir = CONTENT / "posts" / sec_path / post["slug"]
        doc = Doc(manifest, report, src, out_dir, link_map,
                  demote_h1=post.get("demoteH1", True))
        body = doc.body((REPO / src).read_text(encoding="utf-8"))
        if not body.strip():
            if post.get("stub"):
                body = "> 🚧 本章节正在撰写中，内容会随笔记更新同步发布。\n"
            else:
                report.warn(f"{src} 转换后是空文档，却仍被发布")
        elif post.get("stub"):
            report.note(f"{src} 标记了 stub 但已有内容，可以把 status.json 里的 stub 去掉")
        fields = {
            "title": post.get("title"),
            "date": post.get("date"),
            "description": post.get("description"),
            "tags": post.get("tags"),
            "weight": post.get("weight"),
            "pin": post.get("pin"),
            "toc": post.get("toc"),
            "draft": post.get("draft"),
        }
        text = frontmatter_toml(fields) + "\n\n" + header(src) + "\n\n" + body
        outputs.append(Output(out_dir / "index.md", text, doc.images))

    # 固定页面
    for page in manifest.get("pages") or []:
        kind = page.get("kind")
        if kind == "search":
            text = (
                "---\n"
                f"title: {json.dumps(page.get('title') or 'Search', ensure_ascii=False)}\n"
                'layout: "search"\n'
                f"placeholder: {json.dumps(page.get('description') or '搜索笔记…', ensure_ascii=False)}\n"
                "---\n"
            )
            outputs.append(Output(CONTENT / "search.md", text))
        elif kind == "home":
            text = frontmatter_toml({"title": page.get("title")}) + "\n\n"
            src = page.get("source")
            if src:
                doc = Doc(manifest, report, src, CONTENT, link_map)
                text += header(src) + "\n\n" + doc.body((REPO / src).read_text(encoding="utf-8"))
                outputs.append(Output(CONTENT / "_index.md", text, doc.images))
            else:
                outputs.append(Output(CONTENT / "_index.md", text))
        else:
            report.error(f"未知的 page kind: {kind!r}")

    return outputs


def audit_scan_roots(manifest: dict, report: Report) -> None:
    """列出仓库里存在、但没有被清单收录的笔记，提醒是「故意不发」还是「忘了」。"""
    published = {p["source"] for p in manifest.get("posts") or [] if p.get("source")}
    published |= {s["index_source"] for s in manifest.get("sections") or [] if s.get("index_source")}
    published |= {p["source"] for p in manifest.get("pages") or [] if p.get("source")}
    skipped = {s.get("source") for s in manifest.get("skipped") or []}

    for root in manifest.get("scanRoots") or []:
        root_dir = REPO / root
        if not root_dir.is_dir():
            continue
        for path in sorted(root_dir.rglob("*.md")):
            rel = path.relative_to(REPO).as_posix()
            if rel in published or rel in skipped:
                continue
            size = path.stat().st_size
            hint = "空文件" if size == 0 else f"{size} 字节"
            report.warn(
                f"未被 status.json 收录，不会发布: {rel}（{hint}）"
            )


